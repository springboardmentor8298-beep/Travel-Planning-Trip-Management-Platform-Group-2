// Dynamic Image Resolution Generator using category pool rotation & unique seed hashing
export const getDestinationImages = (placeSlug, placeName, category, rawHero, rawGallery) => {
  // 1. Check explicit specific mapping first
  const slugKey = (placeSlug || "").toLowerCase().trim();
  const nameKey = (placeName || "").toLowerCase().trim();

  for (const [key, profile] of Object.entries(DESTINATION_SPECIFIC_IMAGES)) {
    if (slugKey.includes(key) || key.includes(slugKey) || nameKey.includes(key.replace(/-/g, ' '))) {
      return {
        heroImage: profile.hero,
        gallery: profile.gallery
      };
    }
  }

  // 2. Select category pool
  const pool = CATEGORY_IMAGE_POOLS[category] || CATEGORY_IMAGE_POOLS["Heritage & Forts"];
  
  // Calculate deterministic offset hash from placeName/slug
  const hash = (placeSlug || placeName || "dest").split("").reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const heroIndex = hash % pool.length;

  // Build hero image
  const selectedHero = (rawHero && !rawHero.includes("photo-1564507592333-c60657eea523")) ? rawHero : pool[heroIndex];

  // Rotate pool so hero is first and all 10 gallery images are unique to this place
  const rotatedGallery = [];
  for (let i = 0; i < pool.length; i++) {
    const idx = (heroIndex + i) % pool.length;
    rotatedGallery.push(pool[idx]);
  }

  // Combine with any authentic rawGallery items if valid
  const cleanRawGallery = Array.isArray(rawGallery) ? rawGallery.filter(img => typeof img === "string" && !img.includes("photo-1564507592333-c60657eea523")) : [];
  const finalGallery = Array.from(new Set([selectedHero, ...cleanRawGallery, ...rotatedGallery])).slice(0, 10);

  return {
    heroImage: selectedHero,
    gallery: finalGallery
  };
};
